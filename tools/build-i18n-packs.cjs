'use strict';
// i18n-catalog.js remains the only authored catalog. These assets contain data,
// not another translator, and are regenerated after catalog changes.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '..');
function literal(value) {
    if (Object.prototype.toString.call(value) === '[object RegExp]') return value.toString();
    if (Array.isArray(value)) return '[' + value.map(literal).join(',') + ']';
    if (value && typeof value === 'object') return '{' + Object.entries(value).map(([key, item]) => JSON.stringify(key) + ':' + literal(item)).join(',') + '}';
    return JSON.stringify(value);
}
function generate({ check = false } = {}) {
    const source = fs.readFileSync(path.join(ROOT, 'client/i18n-catalog.js'), 'utf8'), context = { window: {} };
    vm.runInNewContext(source, context);
    const catalog = context.window.Drop2TunnelI18nCatalog, config = context.window.Drop2TunnelI18nConfig;
    const version = crypto.createHash('sha256').update(source).digest('hex').slice(0, 16);
    const files = new Map(), englishIndex = config.dynamicLanguages.indexOf('en');
    const base = Object.fromEntries(Object.entries(catalog).map(([key, values]) => [key, { ...(values['zh-Hans'] ? { 'zh-Hans': values['zh-Hans'] } : {}), 'zh-Hant': values['zh-Hant'] || values['zh-Hans'] || key, en: values.en || values['zh-Hans'] || key }]));
    const baseConfig = { ...config, packVersion: version, loadedLanguages: ['zh-Hans', 'zh-Hant', 'en'], templates: config.templates.map(([pattern, values, labels]) => [pattern, config.dynamicLanguages.map((lang, index) => index === englishIndex || lang === 'zh-Hant' ? values[index] : null), ...(labels ? [labels] : [])]) };
    files.set('client/i18n-bootstrap.js', '// Generated by tools/build-i18n-packs.cjs; edit i18n-catalog.js.\n(function(global){\n"use strict";\nglobal.Drop2TunnelI18nCatalog=' + JSON.stringify(base) + ';\nglobal.Drop2TunnelI18nConfig=' + literal(baseConfig) + ';\n})(window);\n');
    for (const [language] of config.languages) {
        if (language === 'zh-Hans' || language === 'en') continue;
        const index = config.dynamicLanguages.indexOf(language);
        files.set('client/i18n/' + language + '.json', JSON.stringify({ version, language, catalog: Object.fromEntries(Object.entries(catalog).map(([key, values]) => [key, values[language] || values.en || key])), templates: config.templates.map(([, values]) => values[index]) }) + '\n');
    }
    for (const [file, body] of files) {
        const target = path.join(ROOT, file);
        if (check) {
            if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body) throw new Error('Stale language asset: ' + file + '; run node tools/build-i18n-packs.cjs');
        } else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, body); }
    }
    return { version, files: [...files.keys()], startupBytes: Buffer.byteLength(files.get('client/i18n-bootstrap.js')), sourceBytes: Buffer.byteLength(source) };
}
if (require.main === module) console.log(JSON.stringify(generate({ check: process.argv.includes('--check') })));
module.exports = { generate };
